CREATE DEFINER=`root`@`localhost` PROCEDURE `BalancePerCustomer`(IN nasabah_name VARCHAR(100))
BEGIN
    SELECT 
        DC.CustomerName,
        DA.AccountType,
        DA.Balance,
        -- Rumus: Balance Awal + (Total Deposit - Total Keluar)
        (DA.Balance + SUM(
            CASE 
                WHEN FT.TransactionType = 'Deposit' THEN FT.Amount 
                ELSE -FT.Amount 
            END
        )) AS CurrentBalance
    FROM 
        DimCustomer DC
    JOIN 
        DimAccount DA ON DC.CustomerID = DA.CustomerID
    JOIN 
        FactTransaction FT ON DA.AccountID = FT.AccountID
    WHERE 
        DC.CustomerName LIKE CONCAT('%', nasabah_name, '%') -- Fitur pencarian nama
        AND DA.Status = 'active'
    GROUP BY 
        DC.CustomerName, 
